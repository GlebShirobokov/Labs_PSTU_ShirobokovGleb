#include <iostream> //подклчение потоковых операций

using namespace std; //использование стандартного пространства имён

const int sizen = 100; //максимальный размер массива

void dlt(int* a, int& n) { //массив принимающий одномерный массив, и его количество
	int p = -1, q = -1, k; //p - начальный индекс 0, q - конечный индекс 0, k - количество символов, которые нужно удалить
	for (int i = 0; i < n; ++i) {
		if (a[i] == 0) { //проверка элемента на 0
			if (p == -1) p = i;
			else {
				q = i; 
				i = n; //окончание цикла
			}
		}
	}
	if (p != -1) {
		if (q != -1) {
			k = q - p - 1; //нахождение количества удаляемых элементов
			for (int i = q; i < n; ++i) {
				a[i - k] = a[i]; // индекс i-k позволит записывать 0 и все чсила идущие после него после первого 0
			}
			n -= k; //уменьшение общего кличества элементов
		}
	}
}

//для функций представленных ниже принцип тот же, просто передаётся другой тип данных массива
