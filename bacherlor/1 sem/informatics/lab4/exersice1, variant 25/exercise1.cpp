#include <iostream> //директива отвечающая за входные, выходные потоки данных


using namespace std; //подключение стандартного прсторанства имём

int main() {
    setlocale(LC_ALL, ".65001");
    const int size{100}; //максимальная длина массива
    int a[size], n, k, st, n1{0};

    cout << "Введите количество элементов массива ";
    cin >> n; //количесво элементов, которое будет использоваться
    cout << "\nВведите элементы массива ";
    for(int i = 0; i < n; ++i) cin >> a[i]; //ввод элементов с клавиатуры

    cout << "\nВведите k ";
    cin >> k; //элемент с которого будет производится распечатка
    st = ((k-1)%n+n)%n; //st начальный элемент распечатки т.к. k-номер элемента, необходимо преревести его в индекс, %n нужно чтобы не выходить за пределы, 
    //  n)%n нужно, чтобы начальный элемент не был отрицательным
    cout << "\nОднонаправленное кольцо: ";
    for(int i =0; i < n; ++i){
        int idx = ((st - i)%n+n)%n; //сами индексы которые будут выводиться
        cout << a[idx] << ' ';
    }

    //в данном блоке кода предстваленная сортировка по убыванию методом обмена
    for(int i = 0; i < n - 1; ++i){
        for(int j = 0; j < n -1; ++j){
            if(a[j] < a[j+1]){
                int tmp = a[j];
                a[j] = a[j+1];
                a[j+1] = tmp;
            }
        }
    }
    //происходит выведение в консоль промежуточных результатов
    cout << "\nОтсортированное по убыванию кольцо: ";
    for(int i = 0; i < n; ++i){
        int idx = ((st - i)%n+n)%n;
        cout << a[idx] << ' ';
    }

    cout << "\nКольцо, состоящее из чётных элементов: ";
    for(int i = 0; i < n; ++i){
        if(a[i] %2 == 0) { //проверка на чётность элементов массива
            a[n1] = a[i]; //n1 изначально 0, мы перезаписываем элементы массива в начало
            ++n1; // затем увеличиваем n1, чтобы перезаписать на следующий индекс
        }
    }
    n = n1;//теперь в нашем массиве не n элементов, а n1 элементов
    //окончатьльный вывод
    for(int i = 0; i <n; ++i){
        int idx = ((st - i)%n+n)%n;
        cout << a[idx] << ' ';
    }
    return 0;
}